import Foundation
import AppKit

public struct CopyFilter: Codable, Equatable {
    // App-level exclusions
    public var excludedBundleIdentifiers: Set<String>
    public var excludedAppNames: Set<String>
    
    // Length restrictions
    public var minLength: Int
    public var maxLength: Int
    
    // Content sanitization
    public var ignoreWhitespaceOnly: Bool
    public var ignoreSequentialDuplicates: Bool
    public var ignoreTransientPasteboardTypes: Bool
    
    // Regex pattern filtering
    public var blockCreditCardNumbers: Bool
    public var blockPrivateKeys: Bool
    public var blockApiKeysAndTokens: Bool
    public var customRegexPatterns: [String]
    
    public init(
        excludedBundleIdentifiers: Set<String> = [
            "com.agilebits.onepassword",
            "com.agilebits.onepassword7",
            "com.1password.1password",
            "com.bitwarden.desktop",
            "com.apple.keychainaccess",
            "org.keepassxc.keepassxc",
            "com.lastpass.LastPass"
        ],
        excludedAppNames: Set<String> = [
            "1Password",
            "Bitwarden",
            "Keychain Access",
            "KeePassXC"
        ],
        minLength: Int = 1,
        maxLength: Int = 200_000,
        ignoreWhitespaceOnly: Bool = true,
        ignoreSequentialDuplicates: Bool = true,
        ignoreTransientPasteboardTypes: Bool = true,
        blockCreditCardNumbers: Bool = true,
        blockPrivateKeys: Bool = true,
        blockApiKeysAndTokens: Bool = false,
        customRegexPatterns: [String] = []
    ) {
        self.excludedBundleIdentifiers = excludedBundleIdentifiers
        self.excludedAppNames = excludedAppNames
        self.minLength = minLength
        self.maxLength = maxLength
        self.ignoreWhitespaceOnly = ignoreWhitespaceOnly
        self.ignoreSequentialDuplicates = ignoreSequentialDuplicates
        self.ignoreTransientPasteboardTypes = ignoreTransientPasteboardTypes
        self.blockCreditCardNumbers = blockCreditCardNumbers
        self.blockPrivateKeys = blockPrivateKeys
        self.blockApiKeysAndTokens = blockApiKeysAndTokens
        self.customRegexPatterns = customRegexPatterns
    }
    
    public enum RejectionReason: String, Error, Equatable {
        case appExcluded = "Source application is in exclusion list"
        case tooShort = "Content below minimum length threshold"
        case tooLong = "Content exceeds maximum length threshold"
        case whitespaceOnly = "Content is whitespace-only"
        case transientPasteboard = "Marked transient/concealed by source application"
        case creditCardDetected = "Credit card number pattern detected"
        case privateKeyDetected = "Private key header detected"
        case apiKeyDetected = "API token / credentials pattern detected"
        case customRegexMatched = "Matched custom filter pattern"
    }
    
    public enum CopyDecision: Equatable {
        case allowed
        case rejected(RejectionReason)
    }
    
    public func shouldCopy(
        content: String,
        sourceBundleId: String?,
        sourceAppName: String?,
        pasteboardTypes: [NSPasteboard.PasteboardType]
    ) -> CopyDecision {
        // 1. Check excluded app bundle IDs
        if let bundleId = sourceBundleId, excludedBundleIdentifiers.contains(bundleId) {
            return .rejected(.appExcluded)
        }
        
        // 2. Check excluded app names
        if let appName = sourceAppName, excludedAppNames.contains(appName) {
            return .rejected(.appExcluded)
        }
        
        // 3. Transient pasteboard types check (macOS convention for password managers)
        if ignoreTransientPasteboardTypes {
            let transientNames = [
                "org.nspasteboard.TransientType",
                "org.nspasteboard.ConcealedType",
                "org.nspasteboard.AutoGeneratedType",
                "com.agilebits.onepassword"
            ]
            for type in pasteboardTypes {
                if transientNames.contains(type.rawValue) {
                    return .rejected(.transientPasteboard)
                }
            }
        }
        
        // 4. Whitespace check
        let trimmed = content.trimmingCharacters(in: .whitespacesAndNewlines)
        if ignoreWhitespaceOnly && trimmed.isEmpty {
            return .rejected(.whitespaceOnly)
        }
        
        // 5. Length limits
        if content.count < minLength {
            return .rejected(.tooShort)
        }
        if content.count > maxLength {
            return .rejected(.tooLong)
        }
        
        // 6. Private keys pattern
        if blockPrivateKeys {
            if content.contains("-----BEGIN PRIVATE KEY-----") ||
               content.contains("-----BEGIN RSA PRIVATE KEY-----") ||
               content.contains("-----BEGIN OPENSSH PRIVATE KEY-----") {
                return .rejected(.privateKeyDetected)
            }
        }
        
        // 7. Credit card numbers (Luhn candidate pattern: 13-19 digits, optional dashes/spaces)
        if blockCreditCardNumbers {
            let ccRegex = #"\b(?:\d[ -]*?){13,16}\b"#
            if content.range(of: ccRegex, options: .regularExpression) != nil {
                // If it passes simple length and digit distribution
                let digits = content.filter { $0.isNumber }
                if digits.count >= 13 && digits.count <= 19 {
                    return .rejected(.creditCardDetected)
                }
            }
        }
        
        // 8. API keys and tokens (e.g. AWS AKIA, GitHub ghp_, JWT tokens)
        if blockApiKeysAndTokens {
            let tokenRegexes = [
                #"AKIA[0-9A-Z]{16}"#,               // AWS Access Key
                #"ghp_[0-9a-zA-Z]{36}"#,            // GitHub personal token
                #"eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"# // JWT
            ]
            for pattern in tokenRegexes {
                if content.range(of: pattern, options: .regularExpression) != nil {
                    return .rejected(.apiKeyDetected)
                }
            }
        }
        
        // 9. Custom user regexes
        for pattern in customRegexPatterns where !pattern.isEmpty {
            if content.range(of: pattern, options: .regularExpression) != nil {
                return .rejected(.customRegexMatched)
            }
        }
        
        return .allowed
    }
}
